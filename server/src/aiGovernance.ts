/**
 * AI Governance & Guardrails Engine for SafeGate 2.0
 * Strict rule enforcement guaranteeing that AI remains 100% advisory
 * and can never execute critical state-altering mutations autonomously.
 */

export type CriticalAction =
  | 'APPROVE_PAYMENT'
  | 'GRANT_GATE_CLEARANCE'
  | 'CHANGE_USER_ROLE'
  | 'MODIFY_ACCESS_PERMISSIONS'
  | 'APPROVE_COMPLIANCE_DOCUMENT'
  | 'OVERRIDE_LOCKDOWN';

export interface GovernanceCheckResult {
  allowed: boolean;
  requiresHumanApproval: boolean;
  reason: string;
  policy: string;
}

export class AIGovernancePolicyEngine {
  private static readonly BLOCKED_AUTONOMOUS_ACTIONS: ReadonlySet<CriticalAction> = new Set([
    'APPROVE_PAYMENT',
    'GRANT_GATE_CLEARANCE',
    'CHANGE_USER_ROLE',
    'MODIFY_ACCESS_PERMISSIONS',
    'APPROVE_COMPLIANCE_DOCUMENT',
    'OVERRIDE_LOCKDOWN',
  ]);

  /**
   * Asserts whether an action is permissible for an autonomous AI actor
   */
  public static evaluateAction(
    action: CriticalAction,
    actorType: 'AI_AGENT' | 'HUMAN_USER',
    userRole?: string
  ): GovernanceCheckResult {
    if (actorType === 'AI_AGENT') {
      if (this.BLOCKED_AUTONOMOUS_ACTIONS.has(action)) {
        return {
          allowed: false,
          requiresHumanApproval: true,
          reason: `Action '${action}' is restricted by SafeGate 2.0 AI Governance Policy. AI agents are strictly advisory.`,
          policy: 'SAFEGATE_AI_SAFETY_SECTION_8',
        };
      }
    }

    // For human users, verify administrative role for security/compliance actions
    if (action === 'CHANGE_USER_ROLE' && userRole !== 'admin' && userRole !== 'secretary') {
      return {
        allowed: false,
        requiresHumanApproval: true,
        reason: 'Only Secretary or Admin can modify role assignments.',
        policy: 'RBAC_ROLE_ESCALATION_PREVENTION',
      };
    }

    return {
      allowed: true,
      requiresHumanApproval: false,
      reason: 'Authorized human operator approved.',
      policy: 'STANDARD_OPERATIONS',
    };
  }

  /**
   * Enforces that an advisory suggestion includes mandatory human confirmation payload
   */
  public static wrapAdvisorySuggestion<T extends Record<string, any>>(
    suggestion: T,
    action: CriticalAction
  ): {
    advisory: true;
    suggestedAction: CriticalAction;
    data: T;
    requiresHumanConfirmation: true;
    disclaimer: string;
  } {
    return {
      advisory: true,
      suggestedAction: action,
      data: suggestion,
      requiresHumanConfirmation: true,
      disclaimer: 'This suggestion is generated by SafeGate AI Advisory Engine. Requires human sign-off.',
    };
  }
}
